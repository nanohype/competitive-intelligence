#!/usr/bin/env node
/**
 * Vendor the eks-agent-platform CRD schemas that `platform.yaml` is validated
 * against, and verify the vendored copies against upstream at the pinned ref.
 *
 *   node scripts/sync-crd-schemas.mjs                 # re-vendor at the pinned ref
 *   node scripts/sync-crd-schemas.mjs --ref=<sha>     # re-vendor and move the pin
 *   node scripts/sync-crd-schemas.mjs --ref=latest    # ...to the newest commit on that path
 *   node scripts/sync-crd-schemas.mjs --check         # the blocking CI gate
 *   node scripts/sync-crd-schemas.mjs --freshness     # is the pin behind upstream? (exit 2 = behind)
 *   node scripts/sync-crd-schemas.mjs --self-test     # prove the freshness report still holds
 *
 * The CRDs are generated by controller-gen in nanohype/eks-agent-platform under
 * `operators/config/crd/bases/`. `platform.yaml` is applied against those exact
 * schemas, so the validator needs them — but resolving them over the network at
 * gate time would make every verdict depend on whatever upstream happens to be
 * that minute, and the tempting failure handler (skip when unreachable) is the
 * exact shape of bug the gate exists to catch. So the copies live here under
 * `schemas/crd/`, and validation is a pure function of the commit under test.
 *
 * That leaves two ways for the copies to become a lie, and `--check` closes
 * both:
 *
 *   1. Tampering. Someone edits a vendored schema — widens an enum, drops a
 *      `required` entry — and the gate happily validates against the weakened
 *      copy, because the gate's only notion of the schema IS that copy.
 *      `schemas/crd/source.json` records a SHA-256 per file;
 *      `scripts/validate-platform-manifests.mjs` verifies every digest before
 *      it reads a single schema, and `--check` here re-verifies them.
 *
 *   2. A stale or hand-moved pin. Someone bumps `upstream.ref` without
 *      re-vendoring, or re-vendors without moving the pin. The digests still
 *      agree with each other while describing a commit whose schemas are
 *      different. `--check` reads each file from upstream AT THE PINNED REF and
 *      requires the bytes to be identical, so the pin and its contents cannot
 *      diverge.
 *
 * Pin fidelity is the whole of the blocking gate, deliberately. Whether the pin
 * is also the newest thing upstream has is a different question with a
 * different answer every day, and answering it here would make a required check
 * flip red because someone pushed to another repository — a verdict about a
 * commit under test must not depend on a commit that is not. `--freshness` asks
 * that question separately and runs on a schedule, never in pull-request CI.
 *
 * Both halves of `--check` fail loudly. An unreadable manifest, a missing
 * vendored file, an unreachable upstream, a checkout that cannot resolve the
 * ref, an unrecognised argument, or a fetched file that is not a CRD all exit
 * non-zero. No path through this script reports success without having
 * compared something.
 *
 * Upstream resolves two ways, both deterministic:
 *   - `$EKS_AGENT_PLATFORM_DIR` — a checkout, read through git objects at the
 *     ref rather than out of its working tree. The ref has to be reachable
 *     there; a checkout that cannot resolve it is an error rather than a silent
 *     substitution of whatever it does hold.
 *   - otherwise — raw.githubusercontent.com at the ref.
 *
 * Re-vendor when the operator's API types change: run with the new `--ref`,
 * review the schema diff, and ship it with whatever `platform.yaml` change it
 * implies.
 *
 * `--ref=latest` resolves the newest upstream commit that touched the vendored
 * path — not the repository's tip — at the moment the re-vendor runs. From a
 * checkout it answers about that clone's history and refuses a commit the pin
 * does not descend from, which is as far as it can go without fetching; CI
 * hands it a fresh default-branch checkout rather than relying on that guard. It exists because the freshness
 * report has to name a remediation that keeps working: the report is copied
 * into an issue body read on whatever day someone opens it, and a commit
 * resolved when the report ran is presented there as the newest one long after
 * it stops being. Naming the command that asks the question, rather than one
 * run's answer, is the difference between an instruction that re-vendors to the
 * newest schemas and one that re-vendors to stale schemas while closing the
 * issue that warned about them. `--self-test` holds that property on the bytes.
 */
import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { copyFile, mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = join(SCRIPT_DIR, "..");
const SCHEMA_DIR = join(ROOT, "schemas", "crd");
const SOURCE_PATH = join(SCHEMA_DIR, "source.json");
const CHECKOUT = process.env.EKS_AGENT_PLATFORM_DIR;
const CHECK = process.argv.includes("--check");
const FRESHNESS = process.argv.includes("--freshness");
const SELF_TEST = process.argv.includes("--self-test");
const REF_ARG = process.argv.find((a) => a.startsWith("--ref="))?.slice("--ref=".length);

const exec = promisify(execFile);
const out = (line) => process.stdout.write(`${line}\n`);
const digest = (buf) => createHash("sha256").update(buf).digest("hex");
const isSha = (value) => typeof value === "string" && /^[0-9a-f]{40}$/.test(value);

function die(message, remedy) {
  process.stderr.write(`\n  ✗ ${message}\n${remedy ? `    ${remedy}\n` : ""}\n`);
  process.exit(1);
}

/**
 * Read the pin manifest. Every rule here exists because breaking it makes the
 * gate's verdict mean less than it appears to.
 */
async function readSourceManifest() {
  let manifest;
  try {
    manifest = JSON.parse(await readFile(SOURCE_PATH, "utf8"));
  } catch (err) {
    die(
      `cannot read schemas/crd/source.json (${err.message})`,
      "The vendored schemas and their source manifest travel together — restore both.",
    );
  }
  const { upstream, files } = manifest;
  if (!upstream?.repository || !upstream?.path) {
    die("schemas/crd/source.json is missing `upstream.repository` or `upstream.path`");
  }
  if (!isSha(upstream.ref)) {
    die(
      "schemas/crd/source.json `upstream.ref` must be a full 40-character commit SHA, got " +
        JSON.stringify(upstream.ref),
      "A branch name would make the gate's verdict depend on when it ran.",
    );
  }
  if (!Array.isArray(files) || files.length === 0) {
    die("schemas/crd/source.json declares no schema files");
  }
  for (const entry of files) {
    if (!entry?.file) die("schemas/crd/source.json has a `files` entry with no `file`");
    if (!/^[0-9a-f]{64}$/.test(entry.sha256 ?? "")) {
      die(`schemas/crd/source.json entry ${entry.file} carries no valid sha256 digest`);
    }
  }
  return manifest;
}

/**
 * Every `.yaml` under schemas/crd/ must be declared. An undeclared schema file
 * is un-digested and un-compared — exactly the blind spot the manifest exists
 * to remove.
 */
async function assertNoUndeclaredSchemas(manifest) {
  const declared = new Set(manifest.files.map((f) => f.file));
  const present = (await readdir(SCHEMA_DIR)).filter((f) => f.endsWith(".yaml"));
  const undeclared = present.filter((f) => !declared.has(f));
  if (undeclared.length > 0) {
    die(
      `schemas/crd/ holds files not declared in source.json: ${undeclared.join(", ")}`,
      "Add them to `files` with digests, or delete them — an undeclared schema is never verified.",
    );
  }
}

/** Resolve an upstream reader for `ref`, failing loudly if it cannot be reached. */
async function upstreamReader(manifest, ref) {
  const { repository, path } = manifest.upstream;

  if (CHECKOUT) {
    let head;
    try {
      const { stdout } = await exec("git", ["-C", CHECKOUT, "rev-parse", "HEAD"]);
      head = stdout.trim();
    } catch (err) {
      die(
        `$EKS_AGENT_PLATFORM_DIR=${CHECKOUT} is not a readable git checkout (${err.message})`,
        `Point it at a checkout of ${repository}, or unset it to read from GitHub instead.`,
      );
    }
    // Reachability, not HEAD equality. What every mode needs is the bytes AT
    // `ref`, and `git show` reads those from the object database whatever the
    // checkout has out or how dirty its working tree is. Requiring HEAD to be
    // the ref would additionally forbid a developer on any other commit from
    // running the gate, while a dirty working tree at the right HEAD would
    // still have been read as upstream.
    try {
      await exec("git", ["-C", CHECKOUT, "cat-file", "-e", `${ref}^{commit}`]);
    } catch {
      die(
        `${ref.slice(0, 12)} is not present in $EKS_AGENT_PLATFORM_DIR=${CHECKOUT} (at ${head.slice(0, 12)})`,
        `Fetch it — a shallow clone of ${repository} cannot answer for a commit it does not have.`,
      );
    }
    return {
      origin: `${CHECKOUT} @ ${ref.slice(0, 12)}`,
      head: ref,
      async read(file) {
        const bytes = await gitShow(CHECKOUT, ref, `${path}/${file}`);
        if (bytes === null) {
          die(
            `${path}/${file} does not exist at ${repository}@${ref.slice(0, 12)}`,
            "The pin predates this CRD, or the file was renamed — re-vendor and repin.",
          );
        }
        return bytes;
      },
    };
  }

  return {
    origin: `${repository}@${ref} (raw.githubusercontent.com)`,
    head: ref,
    async read(file) {
      return await fetchAtRef(repository, path, ref, file);
    },
  };
}

/** Read one schema from raw.githubusercontent.com at `ref`. Never degrades into a skip. */
async function fetchAtRef(repository, path, ref, file) {
  const url = `https://raw.githubusercontent.com/${repository}/${ref}/${path}/${file}`;
  let response;
  try {
    response = await fetch(url);
  } catch (err) {
    die(
      `cannot fetch ${url} (${err.message})`,
      "The upstream comparison is the point of this check — it does not degrade into a skip.",
    );
  }
  if (!response.ok) {
    die(
      `cannot fetch ${url}: HTTP ${response.status} ${response.statusText}`,
      "A ref that no longer resolves is a broken pin, not a passing check.",
    );
  }
  return Buffer.from(await response.arrayBuffer());
}

/**
 * The newest upstream commit that touched the vendored path.
 *
 * One resolver for both callers — the freshness comparison and `--ref=latest` —
 * so what the report measures and what its remediation vendors cannot be two
 * different commits. It resolves the two ways file contents already resolve:
 * from `$EKS_AGENT_PLATFORM_DIR` when that names a checkout, and from GitHub
 * otherwise. Sharing the seam the script already declares is also what lets the
 * whole property be driven against a real repository in `--self-test`.
 *
 * The newest commit touching the PATH, not the repository's tip: repinning onto
 * a commit that changed nothing under `operators/config/crd/bases` would record
 * a ref nobody reviewed a schema diff for, and would leave `--freshness`
 * disagreeing with the pin its own remediation just wrote.
 *
 * Like every other lookup here it fails loudly. "I could not ask" must never
 * become "there is nothing newer".
 */
async function upstreamHead(manifest) {
  const { repository, path } = manifest.upstream;

  if (CHECKOUT) {
    let head;
    try {
      const { stdout } = await exec("git", [
        "-C",
        CHECKOUT,
        "log",
        "-1",
        "--format=%H",
        "--",
        path,
      ]);
      head = stdout.trim();
    } catch (err) {
      die(
        `cannot read the newest commit touching ${path} in $EKS_AGENT_PLATFORM_DIR=${CHECKOUT} (${err.message})`,
        `Point it at a checkout of ${repository}.`,
      );
    }
    if (!isSha(head)) {
      die(
        `no commit touching ${path} is reachable in $EKS_AGENT_PLATFORM_DIR=${CHECKOUT}`,
        "A shallow clone cannot answer this — check the repository out with `fetch-depth: 0`.",
      );
    }
    // A checkout answers about its own history, and nothing here fetches. A
    // clone that predates the pin would name a commit the pin already descends
    // from: as a freshness verdict that reads "current" while upstream has
    // moved, and as `--ref=latest` it would move the pin BACKWARDS onto older
    // schemas. Neither is distinguishable from the truth downstream, so the
    // refusal belongs here.
    if (head !== manifest.upstream.ref) {
      try {
        await exec("git", [
          "-C",
          CHECKOUT,
          "merge-base",
          "--is-ancestor",
          manifest.upstream.ref,
          head,
        ]);
      } catch {
        die(
          `the newest commit touching ${path} in $EKS_AGENT_PLATFORM_DIR=${CHECKOUT} does not descend from the pin ${manifest.upstream.ref.slice(0, 12)}`,
          "Fetch the checkout — a clone that predates the pin cannot say whether the pin is behind.",
        );
      }
    }
    return head;
  }

  // Public repository, so the token is only a rate-limit courtesy: unauthenticated
  // api.github.com is 60 requests an hour per IP, shared across the whole runner
  // fleet, and a lookup that gets throttled must fail rather than guess.
  const token = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN;
  const url =
    `https://api.github.com/repos/${repository}/commits` +
    `?path=${encodeURIComponent(path)}&per_page=1`;
  let response;
  try {
    response = await fetch(url, {
      headers: {
        Accept: "application/vnd.github+json",
        ...(token ? { Authorization: `Bearer ${token}` } : {}),
      },
    });
  } catch (err) {
    die(
      `cannot ask GitHub for the newest commit touching ${path} (${err.message})`,
      "Set $EKS_AGENT_PLATFORM_DIR to a checkout to resolve this without the API.",
    );
  }
  if (!response.ok) {
    die(
      `cannot ask GitHub for the newest commit touching ${path}: HTTP ${response.status} ${response.statusText}`,
      "An unanswerable lookup is not the same as a current pin — it does not degrade into one.",
    );
  }
  const commits = await response.json();
  const head = Array.isArray(commits) ? commits[0]?.sha : undefined;
  if (!isSha(head)) {
    die(`${repository} reports no commit touching ${path}`, "Has the path been renamed upstream?");
  }
  return head;
}

/**
 * Report whether the pin is behind upstream.
 *
 * Deliberately not part of `--check`: the answer changes when someone pushes to
 * eks-agent-platform, so wiring it into pull-request CI would turn an unrelated
 * upstream commit into a red required check on every open branch here. It runs
 * on a schedule instead (`.github/workflows/crd-schema-freshness.yml`), where a
 * red run is a notification that the operator API moved, not a merge blocker.
 *
 * Reads both sides at a ref rather than from a working tree, so a checkout on
 * any commit answers correctly as long as the pinned commit is reachable.
 */
async function reportFreshness(manifest) {
  const { repository, path, ref } = manifest.upstream;
  const tip = await upstreamHead(manifest);
  const behind = [];

  if (CHECKOUT) {
    try {
      await exec("git", ["-C", CHECKOUT, "cat-file", "-e", `${ref}^{commit}`]);
    } catch {
      die(
        `${ref.slice(0, 12)} is not present in $EKS_AGENT_PLATFORM_DIR=${CHECKOUT}`,
        "Check the repository out with full history (fetch-depth: 0) so the pinned commit is reachable.",
      );
    }
    for (const { file } of manifest.files) {
      const [atPin, atTip] = await Promise.all([
        gitShow(CHECKOUT, ref, `${path}/${file}`),
        gitShow(CHECKOUT, tip, `${path}/${file}`),
      ]);
      if (atPin === null) {
        die(
          `${path}/${file} does not exist at ${repository}@${ref.slice(0, 12)}`,
          "The pin predates this CRD, or the file was renamed — re-vendor and repin.",
        );
      }
      if (atTip === null) {
        behind.push(`${file} — removed or renamed upstream since the pin`);
      } else if (!atPin.equals(atTip)) {
        behind.push(`${file} — changed upstream since the pin`);
      }
    }
  } else {
    for (const { file } of manifest.files) {
      const [atPin, atTip] = await Promise.all([
        fetchAtRef(repository, path, ref, file),
        fetchAtRef(repository, path, tip, file),
      ]);
      if (!atPin.equals(atTip)) {
        behind.push(`${file} — changed upstream since the pin`);
      }
    }
  }

  if (behind.length === 0) {
    out(`✓ the pin ${ref.slice(0, 12)} is current with ${path} in ${repository}`);
    return;
  }

  // The verdict names the path that moved and the remediation names a command;
  // neither names the commit this run resolved. What an operator needs is that
  // the pin is behind and what to run — the commit is not something they type,
  // and printing it is what makes this report go stale. It is copied verbatim
  // into an issue body that is re-edited weekly and read on whatever day
  // someone opens it, so a commit resolved here is offered as the newest one
  // for as long as the issue stays open. Following that offer re-vendors to a
  // ref that is no longer newest AND closes the issue warning about it — a
  // wrong instruction that dismisses its own warning. `--ref=latest` resolves
  // upstream when the re-vendor runs, which is the only moment the answer is
  // wanted, so the instruction is correct on every day it is read.
  process.stderr.write(
    `\n  ✗ the pin ${ref.slice(0, 12)} is behind ${path} in ${repository}:\n` +
      `${behind.map((b) => `      ${b}`).join("\n")}\n` +
      "\n    Nothing is broken — the vendored copies still match the commit they claim.\n" +
      "    Adopt the newer operator API when convenient: `npm run schemas:sync -- --ref=latest`,\n" +
      "    review the schema diff, and ship it with whatever platform.yaml change it implies.\n\n",
  );
  // Exit 2, not 1, and the distinction is load-bearing. `die` exits 1 for every
  // way this check can BREAK — an unreachable upstream, a ref that no longer
  // resolves, a fetched file that is not a CRD. "The pin is behind" is a
  // different fact from "I could not find out", and the scheduled workflow files
  // an issue for the first while failing loudly for the second. Collapsed into
  // one code, a month of failed lookups reads as a month of confirmed drift.
  process.exit(2);
}

/** `git show <ref>:<path>` as a Buffer, or null when the path is absent at that ref. */
async function gitShow(dir, ref, path) {
  try {
    const { stdout } = await exec("git", ["-C", dir, "show", `${ref}:${path}`], {
      encoding: "buffer",
      maxBuffer: 64 * 1024 * 1024,
    });
    return stdout;
  } catch {
    return null;
  }
}

/* ────────────────────────────── self-test ───────────────────────────── */

/**
 * Assert what the freshness report SAYS, by running it and reading its bytes.
 *
 * The defect this exists to keep out is not a construction error — the report
 * refreshes correctly every week. It is that a commit resolved at run time and
 * printed unqualified goes on being presented as the newest one until the next
 * run, in an issue body someone opens on an arbitrary day. So the property is
 * about the emitted bytes: no commit the run resolved may appear in what the
 * report prints, and the remediation it names must be a command that resolves
 * upstream when it runs — and must actually do so. What is enforced is that
 * every hex-looking token the report prints, of four characters or more, fails
 * to be a prefix of any commit the fixture resolved, and that no 40-character
 * id appears at all.
 *
 * Coverage is the whole difficulty. An assertion only constrains text a fixture
 * causes to be emitted, so the fixtures here drive every branch of the report a
 * reader can meet: more than one schema behind (the shape a controller-gen
 * regeneration produces), a schema removed upstream, and a pin that is current
 * while upstream has still moved. A leak on a branch no fixture reaches is a
 * leak the gate would call clean.
 *
 * Every case runs against a real git repository built here, through the
 * checkout seam the script already declares, with the script executed as a
 * subprocess in a scratch tree of its own. Driving the real binary is what
 * makes the assertion about the report rather than about a function that
 * happens to feed it, and the scratch tree is what keeps a re-vendor under test
 * from rewriting this repository's own pin.
 */
async function runSelfTest(manifest) {
  const scratch = await mkdtemp(join(tmpdir(), "crd-schemas-selftest-"));
  const cases = [];
  const record = (name, passed, detail) => cases.push({ name, passed, detail });
  const { repository, path } = manifest.upstream;

  const body = (marker) =>
    `apiVersion: apiextensions.k8s.io/v1\nkind: CustomResourceDefinition\nmetadata:\n  name: ${marker}\n`;

  /** A git repository with the vendored path in it, and a helper to commit into it. */
  const upstreamAt = async (name) => {
    const dir = join(scratch, name);
    await mkdir(join(dir, path), { recursive: true });
    const git = (...args) => exec("git", ["-C", dir, ...args]);
    await exec("git", ["init", "-q", "-b", "main", dir]);
    await git("config", "user.email", "self-test@localhost");
    await git("config", "user.name", "self-test");
    await git("config", "commit.gpgsign", "false");
    return {
      dir,
      git,
      async commit(message) {
        await git("add", "-A");
        await git("commit", "-qm", message);
        return (await git("rev-parse", "HEAD")).stdout.trim();
      },
      write: (file, marker) => writeFile(join(dir, path, file), body(marker)),
      drop: (file) => rm(join(dir, path, file)),
    };
  };

  /** A scratch tree holding this script and the vendored schemas, pinned at `ref`. */
  const treeAt = async (name, ref, markers) => {
    const dir = join(scratch, name);
    const schemas = join(dir, "schemas", "crd");
    const bin = join(dir, "scripts", "sync-crd-schemas.mjs");
    await mkdir(join(dir, "scripts"), { recursive: true });
    await mkdir(schemas, { recursive: true });
    await copyFile(fileURLToPath(import.meta.url), bin);
    const files = [];
    for (const { file } of manifest.files) {
      const bytes = Buffer.from(body(markers(file)));
      await writeFile(join(schemas, file), bytes);
      files.push({ file, sha256: digest(bytes) });
    }
    const source = join(schemas, "source.json");
    await writeFile(
      source,
      `${JSON.stringify({ upstream: { repository, path, ref }, files }, null, 2)}\n`,
    );
    return { dir, schemas, source, bin };
  };

  /** Run the script in `tree`, against `up`, and capture what it emitted. */
  const runner =
    (tree, up) =>
    async (...args) => {
      try {
        const { stdout, stderr } = await exec(process.execPath, [tree.bin, ...args], {
          env: { ...process.env, EKS_AGENT_PLATFORM_DIR: up.dir },
          maxBuffer: 64 * 1024 * 1024,
        });
        return { code: 0, output: `${stdout}${stderr}` };
      } catch (err) {
        return {
          code: typeof err.code === "number" ? err.code : 1,
          output: `${err.stdout ?? ""}${err.stderr ?? ""}` || String(err.message ?? err),
        };
      }
    };

  // Which commits the output names, found by comparing the hex-looking tokens
  // in it against the commits the fixture knows — not by scanning for a fixed
  // prefix length. Git's shortest abbreviation is four characters, so a scan
  // anchored at seven misses `slice(0, 6)`; and a scan for a four-character
  // substring would fire on any English word that happens to be hex. Comparing
  // whole tokens against real commits has neither failure. The substring pass
  // that follows catches a longer abbreviation glued to a word, where token
  // boundaries do not fall where the commit starts.
  const hexTokens = (text) => [...text.matchAll(/[0-9a-fA-F]{4,}/g)].map((m) => m[0].toLowerCase());
  const named = (output, forbidden) => {
    const tokens = hexTokens(output);
    const lower = output.toLowerCase();
    return forbidden.filter(
      (sha) => tokens.some((t) => sha.startsWith(t)) || lower.includes(sha.slice(0, 7)),
    );
  };
  const namesNone = (label, output, forbidden) => {
    const leaked = named(output, forbidden);
    record(
      label,
      leaked.length === 0,
      leaked.length > 0 ? `names ${leaked.map((s) => s.slice(0, 12)).join(", ")}` : output.trim(),
    );
  };
  const revendorCommands = (text) =>
    [...text.matchAll(/npm run schemas:sync[^\n`]*/g)].map((m) => m[0].trim());

  try {
    /* ── a behind pin, with more than one schema moved ── */
    const up = await upstreamAt("upstream");
    for (const { file } of manifest.files) await up.write(file, `pinned-${file}`);
    const pin = await up.commit("the schemas as this repo vendored them");

    // Two, because a controller-gen regeneration moves whatever it regenerates
    // and a report that lists several files is the shape production emits. A
    // fixture that only ever moves one leaves every multi-file branch of the
    // report unexecuted, and an assertion over bytes nothing produced is green
    // by vacancy.
    const [movedA, movedB] = manifest.files.map((f) => f.file);
    await up.write(movedA, `moved-${movedA}`);
    await up.write(movedB, `moved-${movedB}`);
    const schemaHead = await up.commit("two schemas gain a bound");

    // ...and a later commit touching nothing under the vendored path. `latest`
    // has to resolve the newest commit that changed the SCHEMAS: repinning onto
    // a busy upstream's tip would record a ref nobody read a schema diff for.
    await writeFile(join(up.dir, "README.md"), "not a schema\n");
    const repoHead = await up.commit("an unrelated change");

    const tree = await treeAt("tree", pin, (file) => `pinned-${file}`);
    const run = runner(tree, up);
    const resolved = [schemaHead, repoHead];

    const behind = await run("--freshness");
    record(
      "a behind pin exits 2, the code the workflow files an issue for",
      behind.code === 2,
      `exit ${behind.code}`,
    );
    record(
      "the report names every schema that moved",
      [movedA, movedB].every((f) =>
        behind.output.includes(`${f} — changed upstream since the pin`),
      ),
      behind.output.trim(),
    );
    namesNone("the report names no commit it resolved", behind.output, resolved);
    record(
      "the report prints no 40-character commit id at all",
      !/[0-9a-fA-F]{40}/.test(behind.output.split(pin).join("")),
      behind.output.trim(),
    );
    record(
      "the report names one re-vendor command, and it resolves upstream when it runs",
      revendorCommands(behind.output).length === 1 &&
        revendorCommands(behind.output)[0] === "npm run schemas:sync -- --ref=latest",
      revendorCommands(behind.output).join(" | ") || behind.output.trim(),
    );

    /* ── and that command has to do what the report says ── */
    const synced = await run("--ref=latest");
    record("`--ref=latest` re-vendors", synced.code === 0, synced.output.trim());
    const repinned = JSON.parse(await readFile(tree.source, "utf8"));
    record(
      "`--ref=latest` lands the pin on the newest commit touching the schemas",
      repinned.upstream.ref === schemaHead,
      `pin is ${repinned.upstream.ref}, the schemas last moved at ${schemaHead}`,
    );
    record(
      "`--ref=latest` vendors the bytes at that commit",
      (await readFile(join(tree.schemas, movedA), "utf8")) === body(`moved-${movedA}`) &&
        (await readFile(join(tree.schemas, movedB), "utf8")) === body(`moved-${movedB}`),
    );
    record(
      "`--ref=latest` rewrites the digests with the bytes",
      [movedA, movedB].every(
        (f) =>
          repinned.files.find((e) => e.file === f)?.sha256 ===
          digest(Buffer.from(body(`moved-${f}`))),
      ),
    );
    const checked = await run("--check");
    record(
      "the re-vendored copies pass the blocking gate at that pin",
      checked.code === 0,
      checked.output.trim(),
    );

    /* ── the current verdict, while upstream has still moved ── */
    // The pin is now the newest commit that changed a vendored schema, and a
    // later commit touches the path without changing one. So the report says
    // "current" while the commit it resolved is not the pin — the one state in
    // which a leak on the ✓ path is distinguishable from printing the pin, and
    // therefore the only state in which asserting on it means anything.
    await up.write("undeclared.yaml", "not vendored here");
    const pathNoise = await up.commit("a CRD this repo does not vendor");
    const current = await run("--freshness");
    record(
      "the pin the remediation lands on reports current",
      current.code === 0,
      current.output.trim(),
    );
    namesNone("the current report names no commit it resolved either", current.output, [
      pathNoise,
      repoHead,
      pin,
    ]);

    /* ── a schema removed upstream: the report's other branch ── */
    const gone = await upstreamAt("upstream-removed");
    for (const { file } of manifest.files) await gone.write(file, `pinned-${file}`);
    const gonePin = await gone.commit("the schemas as this repo vendored them");
    const dropped = manifest.files[manifest.files.length - 1].file;
    await gone.drop(dropped);
    const goneHead = await gone.commit("a vendored schema is removed upstream");
    const goneTree = await treeAt("tree-removed", gonePin, (file) => `pinned-${file}`);
    const runGone = runner(goneTree, gone);

    const removed = await runGone("--freshness");
    record(
      "a schema removed upstream is reported as drift, not as an error",
      removed.code === 2 &&
        removed.output.includes(`${dropped} — removed or renamed upstream since the pin`),
      `exit ${removed.code}: ${removed.output.trim()}`,
    );
    namesNone("the removed-upstream report names no commit it resolved", removed.output, [
      goneHead,
    ]);
    record(
      "`--ref=latest` refuses to vendor a set a declared schema has left",
      (await runGone("--ref=latest")).code === 1,
    );

    /* ── a checkout that predates the pin must not answer ── */
    // Nothing here fetches, so "the newest commit touching the path" is only
    // ever the newest one this clone holds. A clone forked before the pin would
    // otherwise report the pin current while upstream has moved, and `latest`
    // would move the pin backwards onto older schemas.
    const stale = await upstreamAt("upstream-stale");
    for (const { file } of manifest.files) await stale.write(file, `old-${file}`);
    const forked = await stale.commit("before the pin");
    await stale.write(movedA, `pinned-${movedA}`);
    const stalePin = await stale.commit("the commit this repo pins");
    await stale.git("checkout", "-q", "-b", "forked", forked);
    const staleTree = await treeAt("tree-stale", stalePin, (file) => `pinned-${file}`);
    const runStale = runner(staleTree, stale);
    record(
      "a checkout whose newest schema commit predates the pin refuses to report freshness",
      (await runStale("--freshness")).code === 1,
    );
    record(
      "...and refuses to move the pin backwards onto it",
      (await runStale("--ref=latest")).code === 1,
    );

    /* ── the issue body carries the same instruction as the report ── */
    // The report is not the only remediation a reader meets: the scheduled
    // workflow renders it inside a fence and then repeats the instruction under
    // a heading, and the copy under the heading is the one acted on. A rule
    // enforced on one of the two is enforced on the wrong one.
    const workflowPath = join(ROOT, ".github", "workflows", "crd-schema-freshness.yml");
    let workflow = null;
    try {
      workflow = await readFile(workflowPath, "utf8");
    } catch (err) {
      record("the scheduled workflow is where this expects it", false, err.message);
    }
    if (workflow !== null) {
      const inBody = revendorCommands(workflow);
      record(
        "the issue body names the same command the report does",
        inBody.length > 0 && inBody.every((c) => c === "npm run schemas:sync -- --ref=latest"),
        inBody.join(" | ") || "the workflow names no re-vendor command",
      );
      const bodyShas = workflow.match(/\b[0-9a-fA-F]{7,40}\b/g) ?? [];
      record("the issue body names no commit id", bodyShas.length === 0, bodyShas.join(", "));
    }

    /* ── the guards the modes above rest on ── */
    const rejected = async (name, args) => {
      const r = await run(...args);
      record(name, r.code === 1, `exit ${r.code}: ${r.output.trim()}`);
    };
    await rejected("a --ref that is neither a 40-character SHA nor `latest`", [
      `--ref=${schemaHead.slice(0, 12)}`,
    ]);
    await rejected("a --ref naming a commit the checkout does not have", [
      `--ref=${"f".repeat(40)}`,
    ]);
    await rejected("--check and --ref together", ["--check", "--ref=latest"]);
    await rejected("a misspelled mode flag, rather than the re-vendor it is not", ["--selftest"]);
    await rejected("`--ref latest` written with a space, rather than a re-vendor at the pin", [
      "--ref",
      "latest",
    ]);
  } finally {
    await rm(scratch, { recursive: true, force: true });
  }

  const failed = cases.filter((c) => !c.passed);
  out("");
  for (const c of cases) out(`  ${c.passed ? "✓" : "✗"} ${c.name}`);
  if (failed.length > 0) {
    process.stderr.write(
      `\n  ✗ ${failed.length} of ${cases.length} self-test case(s) failed:\n` +
        `${failed.map((c) => `      ${c.name}${c.detail ? ` — ${c.detail}` : ""}`).join("\n")}\n\n`,
    );
    process.exit(1);
  }
  out(`\n✓ all ${cases.length} self-test cases behaved as expected`);
}

async function main() {
  // An unrecognised flag must not fall through to the default mode. That mode
  // rewrites every file under schemas/crd/ and the manifest describing them, so
  // a typo — `--selftest` for `--self-test`, `--ref latest` for `--ref=latest` —
  // would re-vendor and report success instead of saying it did not understand.
  const unknown = process.argv
    .slice(2)
    .filter(
      (a) => !a.startsWith("--ref=") && !["--check", "--freshness", "--self-test"].includes(a),
    );
  if (unknown.length > 0) {
    die(
      `unrecognised argument(s): ${unknown.join(" ")}`,
      "Usage: [--ref=<sha>|--ref=latest] | --check | --freshness | --self-test",
    );
  }

  const modes = [CHECK, FRESHNESS, SELF_TEST, REF_ARG !== undefined].filter(Boolean).length;
  if (modes > 1) die("--check, --freshness, --self-test and --ref are mutually exclusive");
  if (REF_ARG !== undefined && REF_ARG !== "latest" && !isSha(REF_ARG)) {
    die(
      `--ref must be a full 40-character commit SHA or \`latest\`, got ${JSON.stringify(REF_ARG)}`,
      "An abbreviated SHA or a branch name would leave the pin describing something that moves.",
    );
  }

  const manifest = await readSourceManifest();
  await assertNoUndeclaredSchemas(manifest);

  if (SELF_TEST) {
    await runSelfTest(manifest);
    return;
  }

  if (FRESHNESS) {
    await reportFreshness(manifest);
    return;
  }

  // `latest` resolves the newest upstream commit touching the vendored path
  // here, as the re-vendor runs. It is what the freshness report names, so that
  // instruction stays correct however long the issue carrying it has been open.
  const ref =
    REF_ARG === "latest" ? await upstreamHead(manifest) : (REF_ARG ?? manifest.upstream.ref);
  const source = await upstreamReader(manifest, ref);

  const tampered = [];
  const drifted = [];
  const files = [];

  for (const entry of manifest.files) {
    const upstream = await source.read(entry.file);
    if (!upstream.toString("utf8").includes("kind: CustomResourceDefinition")) {
      die(`${entry.file} from ${source.origin} is not a CustomResourceDefinition — refusing it`);
    }
    const localPath = join(SCHEMA_DIR, entry.file);

    if (CHECK) {
      let local;
      try {
        local = await readFile(localPath);
      } catch (err) {
        die(
          `vendored schema schemas/crd/${entry.file} is missing (${err.message})`,
          "Restore it with `npm run schemas:sync`.",
        );
      }
      if (digest(local) !== entry.sha256) {
        tampered.push(
          `${entry.file} — source.json records ${entry.sha256}, on disk ${digest(local)}`,
        );
      }
      if (!local.equals(upstream)) {
        drifted.push(entry.file);
      }
    } else {
      await writeFile(localPath, upstream);
      out(`  ↻ schemas/crd/${entry.file}`);
    }

    files.push({ file: entry.file, sha256: digest(upstream) });
  }

  if (CHECK) {
    if (tampered.length > 0 || drifted.length > 0) {
      if (tampered.length > 0) {
        process.stderr.write(
          "\n  ✗ vendored CRD schemas do not match their recorded digests — they were edited " +
            `in place:\n${tampered.map((t) => `      ${t}`).join("\n")}\n`,
        );
      }
      if (drifted.length > 0) {
        process.stderr.write(
          `\n  ✗ vendored CRD schemas differ from ${source.origin}:\n` +
            `${drifted.map((d) => `      schemas/crd/${d}`).join("\n")}\n`,
        );
      }
      process.stderr.write(
        "\n    Fixes belong upstream in nanohype/eks-agent-platform. To adopt a newer operator\n" +
          "    API here, run `npm run schemas:sync -- --ref=<sha>` and review the schema diff.\n" +
          "    Never hand-edit a file under schemas/crd/.\n\n",
      );
      process.exit(1);
    }
    out(
      `✓ ${manifest.files.length} vendored CRD schemas match their recorded digests and are ` +
        `byte-identical to ${source.origin}`,
    );
    return;
  }

  const pinned = { ...manifest, upstream: { ...manifest.upstream, ref: source.head }, files };
  await writeFile(SOURCE_PATH, `${JSON.stringify(pinned, null, 2)}\n`);
  out(`✓ vendored from ${source.origin}; pin and digests rewritten`);
}

main().catch((err) => {
  process.stderr.write(`\n  ✗ sync-crd-schemas failed: ${err.stack ?? err.message}\n\n`);
  process.exit(1);
});
